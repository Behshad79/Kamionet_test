export const PLACES: GazPlace[] = Object.entries(DATA).flatMap(([province, rows]) =>
  rows.map(([name, lat, lng, kind]) => ({ name, province, lat, lng, kind: kind ?? "city" })),
);

export const KIND_LABEL: Record<PlaceKind, string> = { capital: "مرکز استان", city: "شهر", industrial: "شهرک صنعتی" };

/** Persian/Arabic letter and digit normalisation so "كرج" and "کرج" match. */
export const norm = (s: string) =>
  s
    .replace(/ي/g, "ی")
    .replace(/ك/g, "ک")
    .replace(/[‌\s]+/g, "")
    .replace(/[۰-۹]/g, (d) => String("۰۱۲۳۴۵۶۷۸۹".indexOf(d)))
    .toLowerCase();

const INDEX = PLACES.map((p) => ({ p, key: norm(p.name), prov: norm(p.province) }));
const KIND_RANK: Record<PlaceKind, number> = { capital: 0, city: 1, industrial: 2 };

export function searchPlaces(q: string, limit = 30): GazPlace[] {
  const n = norm(q);
  if (!n) return PLACES.filter((p) => p.kind === "capital");
  const scored: { p: GazPlace; s: number }[] = [];
  for (const { p, key, prov } of INDEX) {
    const i = key.indexOf(n);
    const s = i === 0 ? 0 : i > 0 ? 1 : prov.includes(n) ? 2 : -1;
    if (s >= 0) scored.push({ p, s: s * 10 + KIND_RANK[p.kind] });
  }
  return scored.sort((a, b) => a.s - b.s).slice(0, limit).map((x) => x.p);
}

export const placeByName = (name: string) => PLACES.find((p) => p.name === name);
